export type MessageKey = keyof typeof messages.en;

let currentLang: Lang = 'th';

export function getLang() {
  return currentLang;
}

export function setLang(lang: Lang) {
  currentLang = lang;
  localStorage.setItem('svis_dashboard_lang', lang);
}

export function initLang() {
  const saved = localStorage.getItem('svis_dashboard_lang');
  if (saved === 'en' || saved === 'th') currentLang = saved;
}

export function t(key: MessageKey, vars?: Record<string, string>) {
  let text: string = messages[currentLang][key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(`{${k}}`, v);
    }
  }
  return text;
}
